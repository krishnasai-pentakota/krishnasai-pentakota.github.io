"""Render validated content into dist/.

StrictUndefined is the important line: a typo like {{ profile.nmae }} stops the
build with an error. Jinja's default would quietly print nothing, and you'd ship
a blank heading without noticing.

autoescape turns '<' or '&' in your content into safe HTML, so text can never
break the page or inject a script.

compile_css runs Tailwind's standalone binary through pytailwindcss, so there
is no Node.js anywhere. The version is pinned: the same input always gives the
same CSS, on your laptop and on GitHub Actions.
"""

from __future__ import annotations

import shutil
import subprocess
from datetime import date
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined, select_autoescape

from .models import Site

MARKER = ".built-by-portfolio"
TAILWIND_VERSION = "v4.3.3"


def paragraphs(text: str | None) -> list[str]:
    """Split text on blank lines, so one YAML field can hold several paragraphs."""
    return [p.strip() for p in (text or "").split("\n\n") if p.strip()]


def nicedate(d: date | None) -> str:
    """16 Oct 2026. (strftime's "%-d" doesn't work on Windows, so build it by hand.)"""
    return f"{d.day} {d:%b %Y}" if d else ""


def make_env(templates_dir: Path) -> Environment:
    env = Environment(
        loader=FileSystemLoader(templates_dir),
        autoescape=select_autoescape(("html",)),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.filters["paragraphs"] = paragraphs
    env.filters["nicedate"] = nicedate
    return env


def compile_css(source: Path, output: Path) -> None:
    """Tailwind reads styles/site.css, scans templates/ for class names, and
    writes one minified stylesheet containing only the classes actually used."""
    try:
        from pytailwindcss import run  # imported here so `--check` works without it
    except ImportError:
        import sys
        raise SystemExit(
            "The CSS step needs the 'pytailwindcss' package, which needs Python 3.11 or newer "
            f"(this is Python {sys.version_info.major}.{sys.version_info.minor}).\n"
            "Install Python 3.12 from python.org, then recreate the venv:\n"
            "  py -3.12 -m venv .venv\n  .venv\\Scripts\\Activate.ps1\n  pip install -r requirements.txt"
        ) from None

    output.parent.mkdir(parents=True, exist_ok=True)
    try:
        run(
            ["--input", str(source), "--output", str(output), "--minify"],
            auto_install=True,  # first run downloads the binary (~once per venv)
            version=TAILWIND_VERSION,
        )
    except subprocess.CalledProcessError as e:
        detail = (e.stderr or b"").decode(errors="replace").strip()
        raise SystemExit(f"Tailwind failed to compile {source.name}:\n{detail}") from None


def _clean(out_dir: Path) -> None:
    """Delete the previous build so no stale files survive (an idempotent
    build: same content in, same site out). Refuses to delete a folder this
    tool didn't create, so a wrong --out can't wipe your work."""
    if not out_dir.exists():
        return
    if (out_dir / MARKER).exists() or not any(out_dir.iterdir()):
        shutil.rmtree(out_dir)
    else:
        raise SystemExit(f"Refusing to clear '{out_dir}': it wasn't created by build.py")


def render_site(site: Site, templates_dir: Path, static_dir: Path, styles: Path, out_dir: Path) -> list[Path]:
    env = make_env(templates_dir)
    _clean(out_dir)
    out_dir.mkdir(parents=True)
    (out_dir / MARKER).write_text("Generated by build.py. Safe to delete.\n", encoding="utf-8")
    written: list[Path] = []
    shared = {"site": site, "profile": site.profile, "year": date.today().year}

    def write(template: str, rel: str, current_role=None, **ctx) -> None:
        """Render one page. Every link in the templates is written relative to
        the page, using `root`, the way back to the site root ("" or "../").
        Relative links keep the site working at username.github.io/<repo>/ and
        when you double-click a file on disk. `current_role` lights up the
        matching role in the header."""
        root = "../" * rel.count("/")
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        html = env.get_template(template).render(**shared, root=root, current_role=current_role, **ctx)
        path.write_text(html, encoding="utf-8")
        written.append(path)

    # The opening screen, then one page per role.
    write("index.html", "index.html")
    for role in site.roles:
        template = "hire.html" if role.id == "hire" else "role.html"
        write(template, role.page, current_role=role)

    # Project pages. Previous/next stay inside the project's own role.
    for role in site.roles:
        pages = [p for p in site.pages if p.kind == role.id]
        for i, project in enumerate(pages):
            write("case.html", project.page, current_role=role, project=project,
                  prev=pages[i - 1] if i > 0 else None,
                  next=pages[i + 1] if i + 1 < len(pages) else None)

    hire = site.role("hire")
    if site.resume:
        write("resume.html", "resume.html", current_role=hire, resume=site.resume)
    write("cover-letter.html", "cover-letter.html", current_role=hire)

    # Copy static assets (JS, images, PDFs), then compile CSS on top.
    shutil.copytree(static_dir, out_dir / "static")
    compile_css(styles, out_dir / "static" / "css" / "site.css")
    return [*written, *sorted(p for p in (out_dir / "static").rglob("*") if p.is_file())]
